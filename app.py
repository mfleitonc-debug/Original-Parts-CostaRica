@app.post('/clientes')
@requiere_rol('admin','empleado')
def agregar_cliente():
    nombre = request.form.get('nombre','').strip()
    if not nombre or len(nombre)>150:
        flash('El nombre del cliente es obligatorio (máximo 150 caracteres).')
        return redirect(url_for('inicio'))
